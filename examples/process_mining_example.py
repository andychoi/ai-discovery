# Add project root to path
sys.path.insert(0, str(Path(__file__).parent.parent))

from app.ai.process_miner import ProcessMiner, PseudoLogConverter, mine_scenarios
from app.ai.mining_reporter import MiningReporter


def example_1_single_scenario():
    """Mine a single scenario."""
    print("=" * 70)
    print("Example 1: Single Scenario Mining")
    print("=" * 70)

    # Pseudo event log (as would be generated by ScenarioFlow.generate_pseudo_event_log())
    pseudo_log = {
        "case_id": "scenario_create_order_1",
        "process_name": "Create Order",
        "domain": "Order",
        "events": [
            {"order": 1, "event_name": "Receive Order Request", "event_type": "ENTRY"},
            {"order": 2, "event_name": "Validate Order", "event_type": "PROCESS"},
            {"order": 3, "event_name": "Calculate Price", "event_type": "PROCESS"},
            {"order": 4, "event_name": "Check Inventory", "event_type": "DB"},
            {"order": 5, "event_name": "Save Order", "event_type": "DB"},
            {"order": 6, "event_name": "Publish Order Created Event", "event_type": "QUEUE"},
            {"order": 7, "event_name": "Return Order Response", "event_type": "ENTRY"},
        ],
    }

    # Create miner
    miner = ProcessMiner(
        scenario_id=pseudo_log["case_id"],
        scenario_name=pseudo_log["process_name"],
        domain=pseudo_log["domain"],
    )

    # Run mining
    result = miner.mine_from_pseudo_log(pseudo_log)

    # Print summary
    summary = miner.get_summary()
    print(json.dumps(summary, indent=2))

    # Generate markdown report
    markdown = MiningReporter.generate_markdown_report(result)
    print("\n" + markdown)

    return result


