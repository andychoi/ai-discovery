#!/usr/bin/env python3
"""
Example: Process mining with PM4Py integration.

This example demonstrates how to:
1. Generate pseudo event logs from scenario flows
2. Perform process mining (discovery + conformance)
3. Generate reports and save to disk

Run from project root:
    python examples/process_mining_example.py
or:
    python -m examples.process_mining_example
"""

import json
import sys
