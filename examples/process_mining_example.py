def example_3_save_reports(results: dict):
    """Save mining reports to disk."""
    print("\n" + "=" * 70)
    print("Example 3: Save Reports to Disk")
    print("=" * 70)

    output_dir = Path("./data/mining_reports")

    for scenario_id, result in results.items():
        paths = MiningReporter.save_reports(result, output_dir)
        print(f"\n✓ {scenario_id}")
        print(f"  Markdown: {paths['markdown']}")
        print(f"  JSON: {paths['json']}")

    print(f"\nAll reports saved to: {output_dir}")


def example_4_log_conversion():
    """Demonstrate PseudoLogConverter."""
    print("\n" + "=" * 70)
    print("Example 4: Pseudo Log Conversion")
    print("=" * 70)

    pseudo_log = {
        "case_id": "test_case_1",
        "events": [
            {"order": 1, "event_name": "Start", "event_type": "ENTRY"},
            {"order": 2, "event_name": "Process", "event_type": "PROCESS"},
            {"order": 3, "event_name": "End", "event_type": "ENTRY"},
        ],
    }

    # Convert to PM4Py format
    log = PseudoLogConverter.convert(pseudo_log)

    print(f"✓ Converted to PM4Py EventLog")
    print(f"  Traces: {len(log)}")
    print(f"  Events in first trace: {len(log[0])}")

    for i, event in enumerate(log[0]):
        print(f"    {i+1}. {event.get('concept:name')}")

    return log


