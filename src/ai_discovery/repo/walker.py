"""Repository walker v2 (roadmap item M6.1): which files a scan reads, and why the others are skipped.

One place decides the file set for every stage (language detection, parsing, contract extractors):

- **Listing.** Inside a git work tree, `git ls-files -co --exclude-standard` (tracked + untracked, `.gitignore`
  honoured by git itself). Elsewhere, a filesystem walk honouring every `.gitignore` on the way (gitwildmatch via
  `pathspec`). Symlinked directories are never followed; a symlinked file must resolve inside the root.
- **Excludes are path patterns, not bare names.** Directories that are *always* tooling (`node_modules/`,
  `.git/`, `__pycache__/`, virtualenvs, IDE folders …) are skipped by name. Names that are only *sometimes*
  output are skipped on evidence: `packages/` next to a `.sln`/`packages.config` or holding `.nupkg` files
  (NuGet), `bin/`/`obj/` next to a .NET project, `target/` next to a Maven/sbt/Cargo build, `build/`/`out/`/`dist/`
  unless they are a Python package, `env/` only when it is a virtualenv. A yarn workspace's `packages/` or a
  Python package named `build` is source.
- **User excludes**: `.discoveryignore` at the root and `scan.exclude` (both gitignore syntax).
- **Per-file checks**: size caps (`scan.max_file_kb_source`, `scan.max_file_kb_other`), binary content,
  minified bundles. Generated files (`*.designer.cs`, `*.g.cs`, `@generated` / `<auto-generated>` banners) are
  kept but tagged.
- **Submodules / nested repositories** are skipped unless `scan.submodules` is on.

Every skip is counted by reason (`skipped`) so the scan can record it as a degradation.
"""

from __future__ import annotations

import os
import subprocess
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, Iterator, Optional

try:
    import pathspec
except ImportError:  # pragma: no cover - declared dependency; degrade to no .gitignore in non-git trees
    pathspec = None  # type: ignore[assignment]

LANG_EXTENSIONS: dict[str, frozenset[str]] = {
    "csharp": frozenset({".cs"}),
    "java": frozenset({".java"}),
    "python": frozenset({".py"}),
    "javascript": frozenset({".js", ".ts", ".tsx", ".jsx", ".vue"}),
    "webforms": frozenset({".aspx", ".ascx", ".master", ".asmx", ".ashx", ".asax"}),
    "jsp": frozenset({".jsp", ".jspx", ".tag", ".tagx"}),
    # A-6 import-map tier
    "go": frozenset({".go"}),
    "rust": frozenset({".rs"}),
    "ruby": frozenset({".rb"}),
    "php": frozenset({".php"}),
}
EXT_TO_LANG: dict[str, str] = {ext: lang for lang, exts in LANG_EXTENSIONS.items() for ext in exts}
SOURCE_EXTENSIONS: frozenset[str] = frozenset(EXT_TO_LANG)

MANIFESTS: dict[str, str] = {
    "csproj": "csharp", "sln": "csharp", "pom.xml": "java", "build.gradle": "java", "build.gradle.kts": "java",
    "requirements.txt": "python", "pyproject.toml": "python", "setup.py": "python", "Pipfile": "python",
    "package.json": "javascript", "go.mod": "go", "Cargo.toml": "rust", "Gemfile": "ruby",
    "composer.json": "php",
}

# Directory names that are never source (tooling, caches, dependencies, IDE state).
ALWAYS_SKIP: frozenset[str] = frozenset({
    "node_modules", "__pycache__", ".git", ".hg", ".svn", "venv", ".venv", ".tox", ".nox", ".idea", ".vs",
    ".vscode", "jspm_packages", "bower_components", ".next", ".nuxt", ".svelte-kit", ".astro", ".vercel",
    ".netlify", ".gradle", ".turbo", ".cache", ".parcel-cache", ".eggs", ".direnv", "cdk.out", "coverage",
    ".claude", "generated-sources", "generated-src", ".mypy_cache", ".pytest_cache", ".ruff_cache",
    "vendor", "third_party", "third-party", "migrations",
})
# Names skipped only with evidence that they are build output / package caches (see `_contextual_skip`).
CONTEXTUAL: frozenset[str] = frozenset({"packages", "bin", "obj", "target", "build", "out", "dist", "env",
                                        "publish", "artifacts"})
# Back-compat: the union that the pre-M6.1 walker skipped by bare name (some extractors still glob with it).
LEGACY_SKIP_DIRS: frozenset[str] = ALWAYS_SKIP | CONTEXTUAL | {"assets"}

_GENERATED_SUFFIXES = (".designer.cs", ".g.cs", ".g.i.cs", ".generated.cs", ".generated.ts", ".pb.go", "_pb2.py")
_GENERATED_BANNERS = (b"<auto-generated", b"@generated", b"Code generated", b"DO NOT EDIT", b"This file was generated")
_MINIFIED_SUFFIXES = (".min.js", ".min.mjs", ".min.cjs", ".bundle.js", ".chunk.js")
# Media and archives: no stage reads them, so they are dropped quietly (never a degradation).
_MEDIA = frozenset({".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".ico", ".svgz", ".tif", ".tiff", ".psd",
                    ".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".wav", ".avi", ".mov", ".webm",
                    ".pdf", ".zip", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".jar", ".war", ".ear", ".nupkg",
                    ".dll", ".exe", ".so", ".dylib", ".pdb", ".class", ".pyc", ".o", ".a", ".lib", ".bin"})


@dataclass
class WalkOptions:
    exclude: list[str] = field(default_factory=list)   # gitignore-syntax patterns (scan.exclude)
    max_file_kb_source: int = 2048
    max_file_kb_other: int = 500
    submodules: bool = False

    @classmethod
    def from_config(cls, config) -> "WalkOptions":
        scan = getattr(config, "scan", None)
        if scan is None:
            return cls()
        return cls(list(scan.exclude or []), int(scan.max_file_kb_source), int(scan.max_file_kb_other),
                   bool(scan.submodules))


class RepoWalker:
    """The file set of one repository. ``files()`` lists every kept file once (cached); ``source_files()``
    filters by language; ``skipped`` counts skips by reason with up to five sample paths each."""

    def __init__(self, root: Path, options: Optional[WalkOptions] = None):
        self.root = Path(root)
        self.real_root = self.root.resolve()
        self.options = options or WalkOptions()
        self.skipped: Counter = Counter()
        self.samples: dict[str, list[str]] = {}
        self.generated: set[Path] = set()
        self._files: Optional[list[Path]] = None
        self._dir_cache: dict[Path, Optional[str]] = {}
        user = []
        ignore = self.root / ".discoveryignore"
        if ignore.is_file():
            user += ignore.read_text(encoding="utf-8", errors="replace").splitlines()
        user += self.options.exclude
        self._user_spec = _spec(user)

    # ── public ────────────────────────────────────────────────────────────
    def files(self) -> list[Path]:
        if self._files is None:
            listed = self._git_list()
            if listed is None:
                listed = list(self._fs_list(self.root, []))
            self._files = [p for p in listed if self._keep(p)]
        return self._files

    def source_files(self, languages: Optional[Iterable[str]] = None) -> list[Path]:
        allowed = SOURCE_EXTENSIONS if languages is None else frozenset().union(
            *(LANG_EXTENSIONS[lang] for lang in languages if lang in LANG_EXTENSIONS))
        return [p for p in self.files() if p.suffix.lower() in allowed]

    def skip_reasons(self) -> dict[str, tuple[int, list[str]]]:
        return {k: (v, self.samples.get(k, [])) for k, v in sorted(self.skipped.items())}

    def excluded_dir(self, path: Path) -> bool:
        """Would the walker skip directory *path* (for stages that glob on their own)?"""
        rel = _rel(path, self.root)
        if rel is None:
            return False
        cur = self.root
        for part in rel.parts:
            cur = cur / part
            if self._dir_reason(cur) is not None:
                return True
        return bool(self._user_spec and self._user_spec.match_file(rel.as_posix() + "/"))

    # ── listing ───────────────────────────────────────────────────────────
    def _git_list(self) -> Optional[list[Path]]:
        if not _in_git_tree(self.root):
            return None
        try:
            out = subprocess.run(["git", "-c", "core.quotepath=off", "ls-files", "-co", "--exclude-standard", "-z"],
                                 cwd=self.root, capture_output=True, check=True, timeout=120).stdout
        except (OSError, subprocess.SubprocessError):
            return None
        paths: list[Path] = []
        for raw in sorted({r for r in out.decode("utf-8", errors="replace").split("\0") if r}):
            p = self.root / raw.rstrip("/")
            if raw.endswith("/") or (p.is_dir() and not p.is_symlink()):   # nested repo / submodule gitlink
                if self.options.submodules:
                    paths += RepoWalker(p, self.options)._listing()
                else:
                    self._skip("submodule", p)
                continue
            if not p.exists() and not p.is_symlink():
                continue   # tracked but deleted in the work tree
            paths.append(p)
        return paths

    def _listing(self) -> list[Path]:
        listed = self._git_list()
        return listed if listed is not None else list(self._fs_list(self.root, []))

    def _fs_list(self, d: Path, ignores: list) -> Iterator[Path]:
        gi = d / ".gitignore"
        if gi.is_file():
            spec = _spec(gi.read_text(encoding="utf-8", errors="replace").splitlines())
            if spec is not None:
                ignores = ignores + [(d, spec)]
        try:
            entries = sorted(os.scandir(d), key=lambda e: e.name)
        except OSError:
            return
        for e in entries:
            p = Path(e.path)
            is_dir = e.is_dir(follow_symlinks=False)
            if any(spec.match_file(_rel(p, base).as_posix() + ("/" if is_dir else ""))
                   for base, spec in ignores):
                continue   # .gitignore'd: not a degradation (git would not list it either)
            if e.is_symlink() and e.is_dir():
                self._skip("symlink_dir", p)
                continue
            if is_dir:
                if (p / ".git").exists() and p != self.root and not self.options.submodules:
                    self._skip("nested_repo", p)
                    continue
                yield from self._fs_list(p, ignores)
            else:
                yield p

    # ── decisions ─────────────────────────────────────────────────────────
    def _keep(self, p: Path) -> bool:
        rel = _rel(p, self.root)
        if rel is None:
            return False
        cur = self.root
        for part in rel.parts[:-1]:
            cur = cur / part
            reason = self._dir_reason(cur)
            if reason is not None:
                self._skip(reason, cur, dir_level=True)
                return False
        if self._user_spec is not None and self._user_spec.match_file(rel.as_posix()):
            self._skip("excluded", p)
            return False
        if p.is_symlink():
            try:
                p.resolve().relative_to(self.real_root)
            except (ValueError, OSError):
                self._skip("symlink_outside", p)
                return False
        name = p.name.lower()
        if p.suffix.lower() in _MEDIA:
            return False
        source = p.suffix.lower() in SOURCE_EXTENSIONS
        try:
            size = p.stat().st_size
        except OSError:
            return False
        cap = (self.options.max_file_kb_source if source else self.options.max_file_kb_other) * 1024
        if cap and size > cap:
            self._skip("file_too_large", p)
            return False
        if name.endswith(_MINIFIED_SUFFIXES):
            self._skip("minified", p)
            return False
        if source:
            try:
                with p.open("rb") as fh:
                    head = fh.read(8192)
            except OSError:
                return False
            if b"\0" in head and not head.startswith((b"\xff\xfe", b"\xfe\xff")):   # UTF-16 → encoding fallback
                self._skip("binary", p)
                return False
            if name.endswith((".js", ".mjs", ".cjs")) and size > 2048 and \
                    len(head) / max(1, head.count(b"\n") + 1) > 200:
                self._skip("minified", p)
                return False
            if name.endswith(_GENERATED_SUFFIXES) or any(b in head[:2048] for b in _GENERATED_BANNERS):
                self.generated.add(p)
        return True

    def _dir_reason(self, d: Path) -> Optional[str]:
        if d in self._dir_cache:
            return self._dir_cache[d]
        reason = None
        if d.name in ALWAYS_SKIP:
            reason = "tooling_dir"
        elif d.name in CONTEXTUAL and _contextual_skip(d):
            reason = "build_output"
        self._dir_cache[d] = reason
        return reason

    def _skip(self, reason: str, p: Path, *, dir_level: bool = False) -> None:
        if dir_level:   # count a skipped directory once, however many files it held
            key = ("dir", reason, p)
            if key in self._dir_cache:
                return
            self._dir_cache[key] = reason   # type: ignore[index]
        self.skipped[reason] += 1
        samples = self.samples.setdefault(reason, [])
        if len(samples) < 5:
            rel = _rel(p, self.root)
            samples.append(rel.as_posix() if rel is not None else str(p))


def _contextual_skip(d: Path) -> bool:
    """Is directory *d* (named like build output) really output, on evidence from it and its parent?"""
    name, parent = d.name, d.parent
    try:
        siblings = {e.name for e in os.scandir(parent)}
    except OSError:
        siblings = set()
    has = lambda *suffixes: any(s.endswith(suffixes) for s in siblings)  # noqa: E731
    if name == "packages":   # legacy NuGet package folder, not a JS/TS workspace
        return has(".sln") or "packages.config" in siblings or any(d.glob("*/*.nupkg"))
    if name in ("bin", "obj", "publish", "artifacts"):
        return has(".csproj", ".vbproj", ".fsproj", ".sln") or (d / "Debug").is_dir() or (d / "Release").is_dir() \
            or (d / "project.assets.json").is_file() or any(d.glob("*.dll"))
    if name == "target":
        return bool({"pom.xml", "build.sbt", "Cargo.toml", "build.gradle", "build.gradle.kts"} & siblings) \
            or (d / "classes").is_dir()
    if name == "env":
        return (d / "pyvenv.cfg").is_file() or (d / "bin" / "activate").is_file()
    if name in ("build", "out", "dist"):
        return not (d / "__init__.py").is_file()   # a Python package named `build` is source
    return False


def _spec(lines: list[str]):
    lines = [ln for ln in lines if ln.strip() and not ln.lstrip().startswith("#")]
    if not lines or pathspec is None:
        return None
    if hasattr(pathspec, "GitIgnoreSpec"):   # gitignore semantics (pathspec >= 0.10)
        return pathspec.GitIgnoreSpec.from_lines(lines)
    return pathspec.PathSpec.from_lines("gitwildmatch", lines)


def _rel(p: Path, root: Path) -> Optional[Path]:
    try:
        return p.relative_to(root)
    except ValueError:
        return None


def _in_git_tree(root: Path) -> bool:
    try:
        out = subprocess.run(["git", "rev-parse", "--is-inside-work-tree"], cwd=root, capture_output=True,
                             text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return False
    return out.returncode == 0 and out.stdout.strip() == "true"


# ── module-level API (the old lang_detector / file_walker surface) ────────

def walk_repo(repo_path: Path, languages: Optional[set[str]] = None, *,
              walker: Optional[RepoWalker] = None) -> Iterator[Path]:
    """Source files under *repo_path* for *languages* (all recognised languages when None), sorted."""
    yield from (walker or RepoWalker(Path(repo_path))).source_files(languages)


def detect_languages(repo_path: Path, *, walker: Optional[RepoWalker] = None) -> dict[str, dict]:
    """``{lang: {"file_count", "manifests", "extensions"}}`` over the walker's file set."""
    stats: dict[str, dict] = {}

    def _ensure(lang: str) -> dict:
        return stats.setdefault(lang, {"file_count": 0, "manifests": set(), "extensions": set()})

    for item in (walker or RepoWalker(Path(repo_path))).files():
        ext = item.suffix.lower()
        if ext in EXT_TO_LANG:
            entry = _ensure(EXT_TO_LANG[ext])
            entry["file_count"] += 1
            entry["extensions"].add(ext)
        for key, lang in MANIFESTS.items():
            if item.name == key or item.name.endswith(f".{key}"):
                _ensure(lang)["manifests"].add(key)
    for entry in stats.values():
        entry["manifests"] = sorted(entry["manifests"])
        entry["extensions"] = sorted(entry["extensions"])
    return stats


_WALKERS: dict[Path, RepoWalker] = {}


def excluded_path(path: Path, root: Path) -> bool:
    """For extractors that glob on their own: is any directory of *path* (below *root*) skipped?"""
    root = Path(root)
    walker = _WALKERS.get(root)
    if walker is None:
        if len(_WALKERS) > 32:
            _WALKERS.clear()
        walker = _WALKERS[root] = RepoWalker(root)
    return walker.excluded_dir(Path(path).parent)
