"""Generated agent instructions block for AGENTS.md / CLAUDE.md (roadmap item M5.11).

Deterministic (no LLM, no timestamps): the same scan renders the same bytes.
The block sits between ``BEGIN``/``END`` markers; writing replaces only that
block, and removing it leaves the rest of the file byte-identical. A hard token
cap (default 600, ≈ 4 chars/token) is met by dropping list entries from the tail
(lists are ranked), never by cutting the workflow text.

Agents re-read these files on every session, so every line has to earn its
place: a short map of the codebase and the impact-before-edit workflow.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Optional

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from ..query import overview
from ..query.session import Project

BEGIN = "<!-- ai-discovery:start (generated by `discover mcp install --instructions`; edits inside are replaced) -->"
END = "<!-- ai-discovery:end -->"
DEFAULT_MAX_TOKENS = 600
CHARS_PER_TOKEN = 4
FILES = {"agents": "AGENTS.md", "claude": "CLAUDE.md"}
_LIST_LIMITS = (5, 4, 3, 2, 1, 0)
_BLOCK = re.compile(r"\n*<!-- ai-discovery:start[^\n]*-->\n.*?<!-- ai-discovery:end -->\n?", re.S)


class NotIndexed(RuntimeError):
    pass


def tokens(text: str) -> int:
    return len(text) // CHARS_PER_TOKEN


def _env() -> Environment:
    return Environment(loader=FileSystemLoader(str(Path(__file__).parent / "templates")),
                       undefined=StrictUndefined, keep_trailing_newline=True, autoescape=False)


def _code(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items)


def _facts(project: Project) -> dict:
    ov = overview(project)
    if ov["status"] == "not_indexed":
        raise NotIndexed("no index yet — run `discover scan` first")
    data, meta = ov["data"], ov["meta"]
    counts = data["counts"]
    with project.read() as r:
        screens = [row[0] for row in r.conn.execute(
            "SELECT title FROM pages WHERE scan_id = ? AND type = 'screen' ORDER BY title, page_id",
            (r.scan_id,))] if r.indexed else []
    size_parts = [f"{counts['symbols']} symbols"]
    for key, label in (("endpoints", "endpoints"), ("screens", "screens"), ("tables", "tables"),
                       ("entities", "entity state machines"), ("batch_jobs", "batch jobs")):
        if counts.get(key):
            size_parts.append(f"{counts[key]} {label}")
    return {
        "commit": (meta.get("indexed_commit") or "unknown")[:12],
        "stacks": ", ".join(f"{s['language']} ({s['files']} files)" for s in data["stacks"]) or "none detected",
        "size": " · ".join(size_parts),
        "entry_points": [e["id"] for e in data["entry_points"]],
        "screens": screens,
        "domains": [d["name"] for d in data["domains"]],
    }


def render(project: Project, *, max_tokens: int = DEFAULT_MAX_TOKENS) -> str:
    """The block (markers included), at most *max_tokens*; raises NotIndexed before the first scan."""
    facts = _facts(project)
    template = _env().get_template("instructions.md.j2")
    text = ""
    for n in _LIST_LIMITS:
        text = template.render(begin=BEGIN, end=END, commit=facts["commit"], stacks=facts["stacks"],
                               size=facts["size"], entry_points=_code(facts["entry_points"][:n]),
                               screens=", ".join(facts["screens"][:n]), domains=", ".join(facts["domains"][:n]))
        text = re.sub(r"\n{3,}", "\n\n", text)
        if tokens(text) <= max_tokens:
            return text
    return text  # workflow text alone exceeds the cap: returned whole rather than cut mid-instruction


def _path(repo: Path, which: str) -> Path:
    return repo / FILES[which]


def write(repo: Path, block: str, which: str) -> tuple[Path, str]:
    """Insert or replace the block in AGENTS.md / CLAUDE.md. Returns (path, created|updated|unchanged)."""
    path = _path(repo, which)
    if not path.exists():
        path.write_text(block, encoding="utf-8")
        return path, "created"
    text = path.read_text(encoding="utf-8")
    if _BLOCK.search(text):
        new = _BLOCK.sub(lambda m: ("\n\n" if m.start() else "") + block, text, count=1)
    else:
        new = text.rstrip("\n") + "\n\n" + block
    if new == text:
        return path, "unchanged"
    path.write_text(new, encoding="utf-8")
    return path, "updated"


def remove(repo: Path, which: str) -> tuple[Path, str]:
    """Remove the block. Returns (path, removed|file_removed|absent)."""
    path = _path(repo, which)
    if not path.exists():
        return path, "absent"
    text = path.read_text(encoding="utf-8")
    if not _BLOCK.search(text):
        return path, "absent"
    new = _BLOCK.sub("\n", text, count=1)
    new = new.strip("\n") + "\n" if new.strip() else ""
    if not new:
        path.unlink()
        return path, "file_removed"
    path.write_text(new, encoding="utf-8")
    return path, "removed"


def which_files(spec: Optional[str]) -> list[str]:
    """``agents`` | ``claude`` | ``both`` | ``none``/None → keys of FILES."""
    if spec in (None, "", "none"):
        return []
    if spec == "both":
        return list(FILES)
    if spec in FILES:
        return [spec]
    raise ValueError(f"unknown --instructions value {spec!r}; use agents, claude, both or none")
