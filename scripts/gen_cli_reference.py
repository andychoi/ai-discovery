#!/usr/bin/env python3
"""Generate the README "CLI Reference" from the Typer app (roadmap item M2.7).

    python scripts/gen_cli_reference.py          # rewrite the block in README.md
    python scripts/gen_cli_reference.py --check  # exit 1 if README.md is stale (tests/cli/test_cli_reference.py)

The block lives between the two markers below; everything else in README.md is left alone.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
BEGIN = "<!-- cli-reference:start — generated by scripts/gen_cli_reference.py; do not edit by hand -->"
END = "<!-- cli-reference:end -->"


def _cell(text: str) -> str:
    return " ".join((text or "").split()).replace("|", "\\|")


def _params(cmd) -> list[str]:
    rows = []
    for p in cmd.params:
        if getattr(p, "hidden", False) or p.name in ("help", "install_completion", "show_completion"):
            continue
        if getattr(p, "param_type_name", "") == "argument":   # typer vendors click: no isinstance
            rows.append(f"| `{p.human_readable_name.upper()}` | {_cell(getattr(p, 'help', '') or '')} |")
            continue
        names = ", ".join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])
        default = ""
        if p.default not in (None, False, "", ()) and not p.is_flag:
            default = f" (default: `{p.default}`)"
        rows.append(f"| {names} | {_cell(p.help or '')}{default} |")
    return rows


def render() -> str:
    import typer

    from ai_discovery.cli import app

    root = typer.main.get_command(app)
    out = [BEGIN, "", "Every command takes the global options before or after its name; `--json` prints one JSON "
           "document (errors included) and exit codes follow `docs/roadmap/design/cli-v1.md` §4.", "",
           "**Global options**", "", "| Option | Description |", "|---|---|"]
    out += _params(root)

    def emit(cmd, path: list[str]) -> None:
        if getattr(cmd, "hidden", False):
            return
        name = " ".join(path)
        help_text = (cmd.help or "").strip().split("\n\n")[0]
        out.extend(["", f"### `discover {name}`", "", _cell(help_text), ""])
        rows = _params(cmd)
        if rows:
            out.extend(["| Option | Description |", "|---|---|", *rows])
        if hasattr(cmd, "list_commands"):
            for sub in cmd.list_commands(None):
                emit(cmd.get_command(None, sub), [*path, sub])

    for name in root.list_commands(None):   # registration order (cli/commands/__init__.py)
        emit(root.get_command(None, name), [name])
    out += ["", END]
    return "\n".join(out) + "\n"


def splice(readme: str, block: str) -> str:
    if BEGIN not in readme or END not in readme:
        raise SystemExit(f"README.md has no {BEGIN!r} … {END!r} block")
    head = readme[:readme.index(BEGIN)]
    tail = readme[readme.index(END) + len(END):]
    return head + block.rstrip("\n") + tail


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    current = README.read_text(encoding="utf-8")
    updated = splice(current, render())
    if args.check:
        if updated != current:
            print("README.md CLI reference is stale: run python scripts/gen_cli_reference.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
