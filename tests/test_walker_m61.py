"""Walker v2 (roadmap item M6.1): listing, path-pattern excludes, per-file checks, skip accounting."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

from ai_discovery.repo.walker import RepoWalker, WalkOptions, detect_languages, excluded_path


def _write(root: Path, files: dict[str, str | bytes]) -> None:
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        (p.write_bytes if isinstance(text, bytes) else p.write_text)(text)


def _rels(walker: RepoWalker) -> set[str]:
    return {p.relative_to(walker.root).as_posix() for p in walker.files()}


def test_context_dependent_directories(tmp_path) -> None:
    _write(tmp_path, {
        "package.json": "{}", "packages/api/src/a.js": "x()\n",                       # yarn workspace: source
        "legacy/App.sln": "", "legacy/packages/Newtonsoft/lib/n.cs": "class N {}\n",   # NuGet folder
        "svc/Svc.csproj": "<Project/>", "svc/bin/Debug/x.cs": "", "svc/obj/y.cs": "", "svc/A.cs": "class A {}\n",
        "cli/bin/run.js": "main()\n",                                                     # node `bin/`: source
        "shop/build/__init__.py": "", "shop/build/steps.py": "def f(): pass\n",           # Python package
        "web/build/bundle.js": "a()\n", "web/dist/x.js": "b()\n",                         # build output
        "env/pyvenv.cfg": "", "env/lib/site.py": "", "app/env/__init__.py": "",           # venv vs package
        "node_modules/m/i.js": "", "assets/app.js": "c()\n",
    })
    w = RepoWalker(tmp_path)
    kept = _rels(w)
    for rel in ("packages/api/src/a.js", "svc/A.cs", "cli/bin/run.js", "shop/build/steps.py", "app/env/__init__.py",
                "assets/app.js"):
        assert rel in kept, rel
    for rel in ("legacy/packages/Newtonsoft/lib/n.cs", "svc/bin/Debug/x.cs", "svc/obj/y.cs", "web/build/bundle.js",
                "web/dist/x.js", "env/lib/site.py", "node_modules/m/i.js"):
        assert rel not in kept, rel
    reasons = w.skip_reasons()
    assert reasons["build_output"][0] == 6 and reasons["tooling_dir"][0] == 1   # each directory counted once


def test_gitignore_discoveryignore_and_config_excludes_outside_git(tmp_path) -> None:
    _write(tmp_path, {".gitignore": "*.log\ngen/\n", "sub/.gitignore": "secret.py\n",
                      ".discoveryignore": "legacy/\n", "a.py": "", "gen/b.py": "", "sub/secret.py": "", "sub/ok.py": "",
                      "legacy/old.py": "", "tests/fixtures/big.py": ""})
    w = RepoWalker(tmp_path, WalkOptions(exclude=["tests/fixtures/"]))
    assert {r for r in _rels(w) if r.endswith(".py")} == {"a.py", "sub/ok.py"}
    assert w.skip_reasons()["excluded"][0] == 2       # .gitignore'd files are not degradations


def test_git_work_tree_uses_ls_files(tmp_path) -> None:
    _write(tmp_path, {".gitignore": "out.py\n", "tracked.py": "", "untracked.py": "", "out.py": ""})
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    subprocess.run(["git", "add", "tracked.py", ".gitignore"], cwd=tmp_path, check=True)
    assert {r for r in _rels(RepoWalker(tmp_path)) if r.endswith(".py")} == {"tracked.py", "untracked.py"}


def test_size_binary_minified_and_generated(tmp_path) -> None:
    _write(tmp_path, {"big.py": "x = 1\n" * 2000, "small.py": "x = 1\n", "blob.cs": b"class A {\0}", "utf16.cs": "class U {}".encode("utf-16"),
                      "lib.min.js": "a()", "bundle.js": "var a=1;" * 400,
                      "Form1.Designer.cs": "partial class F {}\n", "proto_pb.py": "# @generated by protoc\nx=1\n"})
    w = RepoWalker(tmp_path, WalkOptions(max_file_kb_source=8))
    assert _rels(w) == {"small.py", "utf16.cs", "Form1.Designer.cs", "proto_pb.py"}
    assert {k: v[0] for k, v in w.skip_reasons().items()} == {"file_too_large": 1, "binary": 1, "minified": 2}
    assert {p.name for p in w.generated} == {"Form1.Designer.cs", "proto_pb.py"}


def test_symlinks_and_nested_repositories(tmp_path) -> None:
    outside = tmp_path / "outside"
    _write(outside, {"o.py": ""})
    root = tmp_path / "repo"
    _write(root, {"a.py": "", "nested/.git/HEAD": "", "nested/n.py": ""})
    os.symlink(outside, root / "linked_dir")
    os.symlink(outside / "o.py", root / "linked.py")
    w = RepoWalker(root)
    assert {r for r in _rels(w) if r.endswith(".py")} == {"a.py"}
    assert set(w.skip_reasons()) == {"symlink_dir", "symlink_outside", "nested_repo"}
    assert "nested/n.py" in _rels(RepoWalker(root, WalkOptions(submodules=True)))


def test_repo_under_a_directory_named_like_output(tmp_path) -> None:
    root = tmp_path / "build" / "packages" / "myrepo"   # ancestors above the root never matter
    _write(root, {"src/a.py": "def f(): pass\n", "api/openapi.yaml": "openapi: 3.0.0\n"})
    assert detect_languages(root)["python"]["file_count"] == 1
    assert not excluded_path(root / "api" / "openapi.yaml", root)
    assert excluded_path(root / "node_modules" / "x" / "openapi.yaml", root)
